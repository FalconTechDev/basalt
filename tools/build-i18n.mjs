// Embeds i18n-src/en.json (Russian source string -> English) into src/basalt-i18n-en.js.
// New Russian UI text: add it to i18n-src/en.json (the key is the exact source string), then run: node tools/build-i18n.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dict = JSON.parse(fs.readFileSync(path.join(root, "i18n-src", "en.json"), "utf8"));
fs.writeFileSync(path.join(root, "src", "basalt-i18n-en.js"), "// generated by tools/build-i18n.mjs from i18n-src/en.json\nwindow.__bsEnDict = " + JSON.stringify(dict) + ";\n");
console.log("basalt-i18n-en.js:", Object.keys(dict).length, "strings");
