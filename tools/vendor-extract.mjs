// Writes the third-party code that can be cut out of src/app.js cleanly into vendor/, and records every library in vendor/MANIFEST.json.
//   node tools/vendor-extract.mjs            (re)write vendor/webpack-modules/*.js, vendor/lucide/icons.js and vendor/MANIFEST.json
//   node tools/vendor-extract.mjs --check    exit 1 when vendor/ no longer matches src/app.js
// Needs only the working tree. What is extracted:
//   * the 195 webpack modules (each one is a self-contained function, so the files are valid JS: an object { id: function })
//   * the Lucide icon table (one object literal)
// What is NOT extracted: the libraries that sit in the application scope (CodeMirror 6, Lezer, yaml, DOMPurify, diff-match-patch, idb, tslib).
// They are top-level `var a=..,b=..;` chains that share one scope with the rest of the application, so a slice is not valid JS on its own.
// They are only located (anchors, byte counts, sha256 of the items) until the editor is rebuilt on upstream releases (docs/REPLACING_INHERITED_CODE.md).
// The extracted files are verified copies. The build does not read them yet; src/app.js stays the single source that runs.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as acorn from "acorn";
import { WEBPACK_GROUPS, APP_LIBS } from "./app-libs.mjs";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const vendor = path.join(root, "vendor");
const src = fs.readFileSync(path.join(root, "src", "app.js"), "utf8");
const sha = (t) => crypto.createHash("sha256").update(t, "utf8").digest("hex");
const ast = acorn.parse(src, { ecmaVersion: 2022 });
const outer = ast.body[0].expression.callee.body.body;
const table = outer[0].declarations[0].init.properties;
const seq = outer[2].expression.expressions;
const appCall = seq[seq.length - 1];
const appBody = appCall.callee.body.body;

// libraries: version / copyright / upstream (from memory of the upstream projects, NOT read from the shipped bytes: the bundler stripped every banner)
const INFO = {
  "crypto-js": { slug: "crypto-js", spdx: "MIT", licence: "crypto-js.txt", version: "3.x or 4.x (not recoverable)", upstream: "https://github.com/brix/crypto-js" },
  "ts-ebml": { slug: "ts-ebml", spdx: "MIT", licence: "ts-ebml.txt", version: "not recoverable", upstream: "https://github.com/legokichi/ts-ebml" },
  "node-polyfills": { slug: "node-polyfills", spdx: "MIT; BSD-3-Clause (ieee754)", licence: "node-polyfills.txt", version: "not recoverable", upstream: "feross/buffer, browserify/events, feross/ieee754, beatgammit/base64-js, kawanet/int64-buffer, feross/is-buffer" },
  "capacitor": { slug: "capacitor", spdx: "MIT", licence: "capacitor.txt", version: "not recoverable", upstream: "https://github.com/ionic-team/capacitor, https://github.com/DirtyHairy/async-mutex" },
  "obsidian-rateapp": { slug: null, spdx: "Obsidian (not third-party)", licence: null, version: "-", upstream: "-" },
  "unified-remark": { slug: "unified-remark", spdx: "MIT", licence: "unified-remark.txt", version: "remark-parse 8.x family (old tokenizer design), exact releases not recoverable", upstream: "https://github.com/remarkjs/remark and https://github.com/syntax-tree, https://github.com/wooorm" },
};
const WEBPACK_KEYS = ["crypto-js", "ts-ebml", "node-polyfills", "capacitor", "obsidian-rateapp"];

const modules = table.map((p) => ({ id: Number(p.key.value ?? p.key.name), text: src.slice(p.start, p.end) }));
const files = new Map(); // relative path -> content
const manifest = { generatedFrom: "src/app.js", note: "see vendor/README.md; versions and copyright holders were not read from the shipped code (banners are stripped) and must be confirmed against the upstream release before a public build", webpackModules: [], appScopeLibraries: [] };

const slots = WEBPACK_GROUPS.map(([name, lic, ids], i) => ({ name, lic, ids: new Set(ids), key: WEBPACK_KEYS[i], mods: [] }));
const remark = { name: "unified/remark family", lic: "MIT", ids: null, key: "unified-remark", mods: [] };
for (const m of modules) (slots.find((s) => s.ids.has(m.id)) || remark).mods.push(m);
for (const g of [...slots, remark]) {
  const info = INFO[g.key];
  const entry = { group: g.name, key: g.key, spdx: info.spdx, version: info.version, upstream: info.upstream, licenseFile: info.licence ? `vendor/licenses/${info.licence}` : null, modules: g.mods.map((m) => m.id), bytes: g.mods.reduce((a, m) => a + m.text.length, 0) };
  if (info.slug) {
    const rel = `webpack-modules/${info.slug}.js`;
    const body = `// ${g.name}\n// Verbatim from the webpack module table of src/app.js (${g.mods.length} modules). Licence: ${info.spdx}, see ../licenses/${info.licence}.\n// Generated by tools/vendor-extract.mjs; do not edit by hand.\nmodule.exports = {\n${g.mods.map((m) => m.text).join(",\n")}\n};\n`;
    files.set(rel, body);
    entry.file = `vendor/${rel}`;
    entry.sha256 = sha(body);
  } else entry.file = null; // Obsidian-written, not vendored
  manifest.webpackModules.push(entry);
}

// Lucide: the first inherited object literal of icons
const lucideLib = APP_LIBS.find(([n]) => n.startsWith("Lucide"));
{
  const start = src.indexOf(lucideLib[2]);
  const end = src.indexOf(lucideLib[3], start);
  let table = null;
  for (const n of appBody) if (n.type === "VariableDeclaration") for (const d of n.declarations) if (d.init && d.init.start === start) table = src.slice(d.init.start, d.init.end);
  if (!table || !table.startsWith('{"a-arrow-down"')) throw new Error("Lucide table not found");
  const body = `// Lucide icon table (1343 icons: name -> [[kind, svg path data], ...]).\n// Verbatim from src/app.js. Licence: ISC for Lucide, MIT for the parts derived from Feather, see ../licenses/lucide.txt.\n// Generated by tools/vendor-extract.mjs; do not edit by hand.\nmodule.exports = ${table};\n`;
  files.set("lucide/icons.js", body);
  manifest.lucide = { file: "vendor/lucide/icons.js", spdx: "ISC; MIT (Feather parts)", licenseFile: "vendor/licenses/lucide.txt", version: "not recoverable (about 1343 icons)", upstream: "https://github.com/lucide-icons/lucide", bytes: table.length, sha256: sha(body), endsBefore: end > 0 };
}

// application-scope libraries: locate only
{
  const items = [];
  for (const n of appBody) {
    if (n.type === "FunctionDeclaration") items.push({ start: n.start, end: n.end });
    else if (n.type === "VariableDeclaration") for (const d of n.declarations) { if (d.init && d.id.type === "Identifier") items.push({ start: d.init.start, end: d.init.end }); }
    else items.push({ start: n.start, end: n.end });
  }
  items.sort((a, b) => a.start - b.start);
  const END = src.indexOf("/*basalt-own:end*/") + "/*basalt-own:end*/".length;
  const isOwn = (t) => /__basaltOwn\./.test(t.slice(0, 200)) || /\/\*own\*\//.test(t.slice(0, 120));
  for (const [name, lic, a, b, after] of APP_LIBS) {
    const s = src.indexOf(a, after ? src.indexOf(after, END) : END);
    let e = b === null ? -1 : src.indexOf(b, s);
    if (e < 0) e = items.find((x) => x.start > src.indexOf('_o.baseTheme({".cm-gutter-lint":{width:"1.4em"', s)).start;
    const own = items.filter((x) => x.start >= s && x.start < e);
    const parts = own.map((x) => src.slice(x.start, x.end)).filter((t) => !isOwn(t));
    manifest.appScopeLibraries.push({ library: name, spdx: lic, items: parts.length, bytes: parts.reduce((x, t) => x + t.length, 0), sha256OfItems: sha(parts.join("\n")), startAnchor: a, endAnchor: b });
  }
}
const manifestText = JSON.stringify(manifest, null, 1) + "\n";
files.set("MANIFEST.json", manifestText);

if (process.argv.includes("--check")) {
  let bad = 0;
  for (const [rel, content] of files) {
    const f = path.join(vendor, rel);
    if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== content) { console.error(`vendor/${rel} is out of date`); bad++; }
  }
  if (bad) process.exit(1);
  console.log(`vendor/ matches src/app.js (${files.size} files)`);
} else {
  for (const [rel, content] of files) {
    const f = path.join(vendor, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, content);
  }
  console.log(`wrote ${files.size} files under vendor/`);
}
