// Renders docs/APP-MAP.md from the structure report of tools/split-app.mjs.
//   node tools/split-app.mjs --md docs/APP-MAP.md     (always analyse the ORIGINAL bundle: pass --file with a base copy, see docs)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const kb = (n) => (n / 1024).toFixed(1) + " KB";
const sum = (a) => a.reduce((s, x) => s + x.size, 0);

export function renderMap(r) {
  let manifest = { base: "?", entries: [] };
  try { manifest = JSON.parse(fs.readFileSync(path.join(root, "src-app", "manifest.json"), "utf8")); } catch (_) {}
  const own = new Set(manifest.entries.map((e) => e.orig));
  const f = r.functions;
  const leaf = f.filter((x) => x.leaf);
  const pending = leaf.filter((x) => !own.has(x.name) && x.size >= 60).sort((a, b) => b.size - a.size);
  const out = [];
  out.push(`# src/app.js map

Generated by \`node tools/split-app.mjs --md docs/APP-MAP.md --file <original app.js>\` (analysed revision: \`${manifest.base}\`, before any own code was spliced in).
Do not edit by hand.

## Shape of the bundle

\`app.js\` is one webpack-style file of ${kb(r.bytes)}:

| part | size | what it is |
| --- | --- | --- |
| package modules (\`var e={134:...}\`) | ${kb(r.packageModules.bytes)} in ${r.packageModules.count} modules | third-party code (markdown parsing, unified/remark helpers, ...) |
| application scope | ${kb(r.appBytes)} | one function scope that holds everything below |
| - top-level \`function\` declarations | ${f.length} (${kb(sum(f))}) | helpers: paths, formatting, geometry, CodeMirror/YAML glue, tslib |
| - top-level \`class\` declarations | ${r.classes.length} (${kb(sum(r.classes))}) | |
| - \`X.prototype.y=\` groups at top level | ${r.protoGroups.length} (${kb(sum(r.protoGroups))}) | |
| - \`var\` statements | ${r.varCount} declarators (${kb(r.varBytes)}) | by far the biggest part: classes written as \`var X=function(){...}()\`, bundled libraries (CodeMirror 6, Lezer, yaml, moment), constant tables |

Because everything lives in a single scope, a function can be replaced in place without touching its callers: keep the declaration (same name and parameters) and change its body.

## Leaf analysis

A function is **leaf** when, after a real scope analysis, it only uses JavaScript built-ins, constants made of literals, and other leaf functions: no DOM, no Electron, no application state.

* functions: ${f.length}, of them leaf: ${leaf.length} (${kb(sum(leaf))}), with no dependency at all: ${f.filter((x) => x.selfContained).length}
* leaf functions already replaced by own code: ${own.size} (${kb(f.filter((x) => own.has(x.name)).reduce((s, x) => s + x.size, 0))} of the original text)

A large share of the remaining leaf functions is third-party code (CodeMirror, Lezer, yaml, tslib helpers): those go away when the libraries themselves are replaced, not by hand-rewriting.

## Rewrite order

| step | module | what goes in | status |
| --- | --- | --- | --- |
| a | pure utilities | path/name helpers, link text, string/array/number utils, dates, colour, binary, geometry, fuzzy scoring, frontmatter glue | **${own.size} functions replaced** (src-app/path.js, text.js, misc.js, frontmatter.js, search.js) |
| b | vault / file model | \`TAbstractFile\`/\`TFile\`/\`TFolder\`, \`Vault\`, adapters (\`FileSystemAdapter\` Electron + \`CapacitorAdapter\`), \`FileManager\` rename/link rewrite | next |
| c | workspace / leaf / tab model | \`Workspace*\` classes (\`WorkspaceItem/Parent/Split/Tabs/Leaf/Root/Window/Floating/Sidedock/Ribbon\`), layout (de)serialisation, \`ViewRegistry\` | |
| d | editor | CodeMirror 6 glue, \`Editor\` API wrapper (\`cP\` class and the \`IA/OA/Fq/Nq\` position helpers), live preview, markdown view | |
| e | settings | settings tabs, hotkeys, appearance, \`Setting\` components | |
| f | plugin API | the exported \`obsidian\` module (\`n.d(d,{...})\`): \`Plugin\`, \`Modal\`, \`Notice\`, components, the helper functions below | |

The plugin-facing helper functions are the names exported by the API module, with their minified names in this build:
\`normalizePath\`=cu, \`debounce\`=wc, \`getLinkpath\`=ET, \`parseLinktext\`=MT, \`fuzzySearch\`=Dy, \`prepareQuery\`=My, \`prepareFuzzySearch\`=Sy, \`prepareSimpleSearch\`=Oy,
\`sortSearchResults\`=Ay, \`parseFrontMatterTags/Aliases/Entry/StringArray\`=iT/nT/eT/tT, \`resolveSubpath\`=FT, \`stripHeading\`=LT, \`stripHeadingForLink\`=IT,
\`arrayBufferToHex\`=Af, \`hexToArrayBuffer\`=Df, \`getBlobArrayBuffer\`=Sc, \`parsePropertyId\`=tY, \`renderMatches\`=Ny.

## Classes (top level)

| name | extends | methods | size |
| --- | --- | --- | --- |
${r.classes.sort((a, b) => b.size - a.size).map((c) => `| ${c.name} | ${c.ext || ""} | ${c.methods} | ${kb(c.size)} |`).join("\n")}

## Prototype groups (top-level \`X.prototype.y=\`)

${r.protoGroups.map((g) => `* ${g.name}: ${g.members} members, ${kb(g.size)}`).join("\n")}

## Leaf functions not replaced yet (60 bytes and up)

Sorted by size. Most are library internals; the app-specific ones are the candidates for the next round (they need either more dependencies ported first, or are DOM-light and belong to steps b-f).

| function | size | deps | constants used |
| --- | --- | --- | --- |
${pending.slice(0, 80).map((x) => `| ${x.name} | ${x.size} B | ${x.deps.join(", ")} | ${x.constDeps.join(", ")} |`).join("\n")}

## Replaced functions

| original | own function |
| --- | --- |
${manifest.entries.map((e) => `| ${e.orig} | ${e.use} |`).join("\n")}
`);
  return out.join("\n");
}
